def build_qbank(path, title, rows_data):
    wb = openpyxl.Workbook()
    wb.properties.title = title
    ws = wb.active
    ws.title = "题库"
    # 表头（加粗，与平台导出样式一致）
    for c, name in enumerate(HEADER):
        cell = ws.cell(row=1, column=c + 1, value=name)
        cell.font = Font(bold=True)
        cell.alignment = Alignment(horizontal="center", vertical="center")
    # 数据行（文本类型，长文本列自动换行）
    wrap = Alignment(wrap_text=True, vertical="top")
    for r, row in enumerate(rows_data, start=2):
        for c, val in enumerate(row):
            cell = ws.cell(row=r, column=c + 1, value=str(val))
            if c in (1, 9, 10):  # 题干 / 参考答案 / 解析
                cell.alignment = wrap
    # 列宽（与平台导出一致：题干 60，其余 16）
    for i in range(len(HEADER)):
        ws.column_dimensions[openpyxl.utils.get_column_letter(i + 1)].width = 60 if i == 1 else 16
    # 填写说明 sheet
    guide = wb.create_sheet("填写说明")
    for i, tip in enumerate(TIPS):
        guide.cell(row=i + 1, column=1, value=tip)
    guide.column_dimensions["A"].width = 120 * 1  # 120 字符宽
    wb.save(path)
    print("XLSX OK:", path, len(rows_data), "questions")


